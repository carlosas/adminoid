def translate(message, lang='en'):
    if lang!='es' or not isinstance(message,str):return message
    if message in MESSAGES:return MESSAGES[message]
    prefixes={'Verified backup: ':'Copia verificada: ','Read-only option: ':'Opción no editable: ','Duplicate INI key: ':'Clave INI duplicada: '}
    for en,es in prefixes.items():
        if message.startswith(en):return es+message[len(en):]
    suffixes={': must be yes/no.':': debe ser sí/no.',': invalid number.':': número inválido.',': must be an integer.':': debe ser entero.',': outside allowed limits.':': fuera de límites.',': invalid option.':': opción inválida.',': invalid text.':': texto inválido.'}
    for en,es in suffixes.items():
        if message.endswith(en):return message[:-len(en)]+es
    if message.startswith('WorkshopItems:'):return 'WorkshopItems: IDs numéricos separados por ;'
    if message.startswith('systemd could not '):return 'systemd no pudo completar la operación solicitada sobre el servicio.'
    return message
